import type { FrameVersion, StoryFrame } from "./types";

export function downloadTextFile(filename: string, content: string, mimeType: string): void {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

function loadImageElement(url: string): Promise<HTMLImageElement | null> {
  return new Promise((resolve) => {
    const img = new Image();
    img.crossOrigin = "anonymous";
    img.onload = () => resolve(img);
    img.onerror = () => resolve(null);
    img.src = url;
  });
}

function wrapTextLines(
  ctx: CanvasRenderingContext2D,
  text: string,
  maxWidth: number,
): string[] {
  const lines: string[] = [];
  let line = "";
  for (const ch of Array.from(text)) {
    const testLine = line + ch;
    if (ctx.measureText(testLine).width > maxWidth && line.length > 0) {
      lines.push(line);
      line = ch;
    } else {
      line = testLine;
    }
  }
  if (line) {
    lines.push(line);
  }
  return lines;
}

export async function exportLongStripPng(params: {
  projectTitle: string;
  frames: StoryFrame[];
  versions: FrameVersion[];
  totalCostUsd: number;
  traceId: string;
}): Promise<void> {
  const { projectTitle, frames, versions, totalCostUsd, traceId } = params;
  const sorted = [...frames].sort((a, b) => a.frame_index - b.frame_index);
  const versionMap = new Map(versions.map((v) => [v.id, v]));

  const canvasWidth = 1080;
  const padding = 48;
  const contentWidth = canvasWidth - padding * 2;
  const headerHeight = 128;
  const footerHeight = 84;
  const imgHeight = 560;
  const captionHeight = 148;
  const cardGap = 36;
  const cardHeight = imgHeight + captionHeight;
  const canvasHeight =
    headerHeight + sorted.length * (cardHeight + cardGap) + footerHeight;

  const canvas = document.createElement("canvas");
  canvas.width = canvasWidth;
  canvas.height = Math.max(400, canvasHeight);
  const ctx = canvas.getContext("2d");
  if (!ctx) {
    throw new Error("Canvas 2D context unavailable");
  }

  ctx.fillStyle = "#0b0d12";
  ctx.fillRect(0, 0, canvas.width, canvas.height);

  ctx.fillStyle = "#edf1f7";
  ctx.font = "bold 32px sans-serif";
  ctx.fillText(projectTitle, padding, 64);

  ctx.fillStyle = "#93a0b8";
  ctx.font = "16px monospace";
  ctx.fillText(
    `EchoCanvas Storyboard · ${sorted.length} Frames · Cost $${totalCostUsd.toFixed(4)} · Trace ${traceId}`,
    padding,
    98,
  );

  let y = headerHeight;
  for (const frame of sorted) {
    const activeVer =
      (frame.active_version_id ? versionMap.get(frame.active_version_id) : undefined) ||
      versions.filter((v) => v.frame_id === frame.id).slice(-1)[0];

    ctx.fillStyle = "#141923";
    ctx.strokeStyle = "#293246";
    ctx.lineWidth = 2;
    ctx.fillRect(padding, y, contentWidth, cardHeight);
    ctx.strokeRect(padding, y, contentWidth, cardHeight);

    const img = activeVer ? await loadImageElement(activeVer.image_url) : null;
    if (img) {
      const scale = Math.min(contentWidth / img.width, imgHeight / img.height);
      const dw = img.width * scale;
      const dh = img.height * scale;
      const dx = padding + (contentWidth - dw) / 2;
      const dy = y + (imgHeight - dh) / 2;
      ctx.drawImage(img, dx, dy, dw, dh);
    } else {
      ctx.fillStyle = "#19202e";
      ctx.fillRect(padding, y, contentWidth, imgHeight);
      ctx.fillStyle = "#8a96ad";
      ctx.font = "18px sans-serif";
      const label = activeVer
        ? `Frame ${frame.frame_index} (Preview protected by external image CORS)`
        : `Frame ${frame.frame_index} (Not yet rendered)`;
      ctx.fillText(label, padding + 28, y + imgHeight / 2);
    }

    const capY = y + imgHeight + 34;
    ctx.fillStyle = "#a5b4fc";
    ctx.font = "bold 18px monospace";
    const scoreTxt =
      activeVer?.vlm_score != null ? ` · VLM ${activeVer.vlm_score.toFixed(1)}` : "";
    ctx.fillText(
      `FRAME ${String(frame.frame_index).padStart(2, "0")} · ${frame.script_json.shot_type} / ${frame.script_json.camera_angle}${scoreTxt}`,
      padding + 24,
      capY,
    );

    ctx.fillStyle = "#e2e8f0";
    ctx.font = "18px sans-serif";
    const actionLines = wrapTextLines(
      ctx,
      frame.script_json.dialogue
        ? `“${frame.script_json.dialogue}” — ${frame.script_json.action}`
        : frame.script_json.action,
      contentWidth - 48,
    ).slice(0, 3);
    actionLines.forEach((line, idx) => {
      ctx.fillText(line, padding + 24, capY + 34 + idx * 28);
    });

    y += cardHeight + cardGap;
  }

  ctx.fillStyle = "#64748b";
  ctx.font = "14px monospace";
  ctx.fillText("Generated by EchoCanvas Multi-Modal Visual Narrative Engine", padding, y + 28);

  const blob = await new Promise<Blob | null>((resolve) =>
    canvas.toBlob((b) => resolve(b), "image/png"),
  );
  if (!blob) {
    throw new Error("Failed to export canvas PNG blob");
  }
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `${projectTitle.replace(/\s+/g, "_")}_storyboard.png`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
